import { z } from 'zod';
export const id = z.string().regex(/^[A-Za-z0-9_-]{1,80}$/);
export const hash = z.string().regex(/^[a-f0-9]{64}$/);
export const selectionSchema = z.tuple([z.number().int().nonnegative(),z.number().int().positive()]).refine(([a,b])=>b>a);
export const measurementSchema = z.object({measurement_id:id,value:z.number().finite(),unit:z.enum(['dBFS','dB','Hz','ratio','samples'])}).strict();
export const patchSchema = z.object({stage_id:id,parameter_id:id,unit:z.enum(['dB','dBFS','Hz','ratio','Q','ms','boolean']),value:z.union([z.number().finite(),z.boolean()])}).strict();
export const proposalSchema = z.object({schema_version:z.literal(1),request_id:id,session_revision:z.number().int().nonnegative(),source_sha256:hash,base_graph_sha256:hash,selection_samples:selectionSchema,hypotheses:z.array(z.string().min(1).max(500)).min(1).max(8),evidence_refs:z.array(measurementSchema).min(1).max(32),parameter_patch:z.array(patchSchema).min(1).max(8),expected_tradeoffs:z.array(z.string().min(1).max(500)).min(1).max(8),limitations:z.array(z.string().min(1).max(500)).min(1).max(8),requires_user_acceptance:z.literal(true)}).strict();
export const snapshotSchema=z.object({session_id:id,session_revision:z.number().int().nonnegative(),source_sha256:hash,base_graph_sha256:hash,source_handle:id,selection_samples:selectionSchema,sample_rate:z.number().int().min(8000).max(192000),parameters:z.array(z.object({stage_id:id,parameter_id:id,unit:patchSchema.shape.unit,value:patchSchema.shape.value,min:z.number().finite(),max:z.number().finite()}).strict()).max(64)}).strict();
export const baselineMetricsSchema=z.object({rms:z.number().finite().nonnegative(),peak:z.number().finite().nonnegative(),alignment_samples:z.union([z.literal(0),z.literal(32)]),binding:snapshotSchema.pick({session_id:true,session_revision:true,source_sha256:true,base_graph_sha256:true,selection_samples:true,sample_rate:true})}).strict();
export const previewSchema=z.object({preview_id:id,audio_sha256:hash,session_revision:z.number().int().nonnegative(),measurements:z.array(measurementSchema).min(1).max(32)}).strict();
export const requestSchema=z.object({schema_version:z.literal(1),request_id:id,session_id:id,prompt:z.string().min(1).max(8192)}).strict();
export const renderInput=z.object({parameter_patch:z.array(patchSchema).min(1).max(8)}).strict();
export const previewInput=z.object({preview_id:id}).strict();
export const emptyInput=z.object({}).strict();
export type Snapshot=z.infer<typeof snapshotSchema>;
export type Measurement=z.infer<typeof measurementSchema>;
export type Patch=z.infer<typeof patchSchema>;
export type Proposal=z.infer<typeof proposalSchema>;
export type Preview=z.infer<typeof previewSchema>;
export type RequestInput=z.infer<typeof requestSchema>;
export type Usage={tool_calls:number;
candidate_frames:number;
input_tokens:number;
output_tokens:number;
cost_usd:number;
latency_ms:number};
export type Envelope={schema_version:1;
request_id:string;
status:'ready'|'noop'|'abstain'|'canceled'|'timed_out'|'failed';
proposal:Proposal|null;
preview:Preview|null;
reason:string|null;
usage:Usage;
trace_id:string;
evidence_refs:Measurement[]};
export interface NativeAdapter { renderFrameCost?(snapshot:Snapshot,signal:AbortSignal):Promise<number>;
 verifyPreview?(snapshot:Snapshot,preview:Preview,signal:AbortSignal):Promise<void>;
 deleteSession?(sessionId:string):Promise<void>;
 snapshot(sessionId:string,signal:AbortSignal):Promise<unknown>;
 measurements(snapshot:Snapshot,signal:AbortSignal):Promise<unknown>;
 render(snapshot:Snapshot,patch:Patch[],signal:AbortSignal):Promise<unknown>;
 compare(snapshot:Snapshot,preview:Preview,signal:AbortSignal):Promise<unknown>;
 }
