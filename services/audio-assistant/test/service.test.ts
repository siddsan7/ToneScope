test('loopback broker requires bearer capability, no Origin, and session authorization',async()=>{const x=await setup();
const token='t'.repeat(48);
const broker=createBroker(x.service,x.store,token,new Set(['session_1']));
try{const address=await listenLoopback(broker);
if(!address||typeof address==='string')throw Error('address');
const url='http://127.0.0.1:'+address.port;
assert.equal((await fetch(url+'/v1/request',{method:'POST',body:JSON.stringify(request)})).status,401);
assert.equal((await fetch(url+'/v1/request',{method:'POST',headers:{Authorization:'Bearer '+token,Origin:'http://evil'},body:JSON.stringify(request)})).status,401);
assert.equal((await fetch(url+'/v1/request',{method:'POST',headers:{Authorization:'Bearer '+token},body:JSON.stringify({...request,session_id:'other'})})).status,403);
const response=await fetch(url+'/v1/request',{method:'POST',headers:{Authorization:'Bearer '+token},body:JSON.stringify(request)});
assert.equal(response.status,200);
assert.equal((await response.json()).status,'ready');
}finally{broker.closeAllConnections();
await new Promise<void>(resolve=>broker.close(()=>resolve()));
await x.cleanup();
}});


